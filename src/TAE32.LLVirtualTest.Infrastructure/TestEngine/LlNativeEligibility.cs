using System.Collections.Concurrent;
using System.Text.RegularExpressions;
using TAE32.LLVirtualTest.Core.Models;

namespace TAE32.LLVirtualTest.Infrastructure.TestEngine;

/// <summary>Host execution helpers (fault/skip heuristics). Generation no longer marks Unsupported.</summary>
internal static class LlNativeEligibility
{
    private static readonly ConcurrentDictionary<string, (long Ticks, string Text)> HeaderCache = new();

    /// <summary>Reserved for future hard stops only; host harness now supports pointers, REG_OFFSET, CAN wait.</summary>
    public static string? DescribeSkip(
        string functionName,
        string? sourceFile,
        IReadOnlyList<LlTestParameterValue> parameters)
        => null;

    public static bool IsHostAddressFault(Exception ex)
    {
        var text = ex.ToString();
        return text.Contains("AccessViolation", StringComparison.OrdinalIgnoreCase)
               || text.Contains("-1073741819", StringComparison.Ordinal);
    }

    public static bool IsAutoClearCheckRegisterMiss(string? caseName, string? peripheralName, bool isAutoGenerated, IReadOnlyList<LlTestAssertionResult> results)
    {
        if (!isAutoGenerated) return false;
        if (string.Equals(peripheralName, "GPIO", StringComparison.OrdinalIgnoreCase)) return false;
        if (caseName is null || !caseName.Contains("clear-check", StringComparison.OrdinalIgnoreCase))
            return false;

        var failed = results.Where(a => !a.Passed).ToList();
        return failed.Count > 0 && failed.All(a =>
            (a.Message ?? "").Contains("寄存器", StringComparison.Ordinal));
    }

    private static bool HasUnsafePointer(IReadOnlyList<LlTestParameterValue> parameters)
        => parameters.Any(p =>
            p.Type.Contains('*')
            && !TestHarnessGenerator.IsPeripheralTypeDefPointer(p)
            && !(p.Type.Contains("char", StringComparison.OrdinalIgnoreCase) && p.Type.Contains('*')));

    internal static string? TryReadInlineBody(string? filePath, string functionName)
    {
        if (string.IsNullOrWhiteSpace(filePath) || string.IsNullOrWhiteSpace(functionName))
            return null;
        if (!File.Exists(filePath))
            return null;

        var text = ReadHeader(filePath);
        var marker = functionName + "(";
        var searchFrom = 0;
        while (searchFrom < text.Length)
        {
            var idx = text.IndexOf(marker, searchFrom, StringComparison.Ordinal);
            if (idx < 0) return null;

            var paren = idx + functionName.Length;
            var brace = text.IndexOf('{', paren);
            if (brace < 0) return null;

            var between = text[paren..brace];
            searchFrom = idx + marker.Length;
            if (between.Contains(';'))
                continue;

            var body = ExtractBalanced(text, brace);
            if (body is null) return null;
            body = Regex.Replace(body, @"/\*.*?\*/", "", RegexOptions.Singleline);
            body = Regex.Replace(body, @"//.*?$", "", RegexOptions.Multiline);
            return body;
        }

        return null;
    }

    private static string ReadHeader(string filePath)
    {
        var ticks = File.GetLastWriteTimeUtc(filePath).Ticks;
        if (HeaderCache.TryGetValue(filePath, out var cached) && cached.Ticks == ticks)
            return cached.Text;
        var text = File.ReadAllText(filePath);
        HeaderCache[filePath] = (ticks, text);
        return text;
    }

    private static string? ExtractBalanced(string text, int openBrace)
    {
        var depth = 0;
        for (var i = openBrace; i < text.Length; i++)
        {
            if (text[i] == '{') depth++;
            else if (text[i] == '}')
            {
                depth--;
                if (depth == 0)
                    return text[openBrace..(i + 1)];
            }
        }
        return null;
    }
}
