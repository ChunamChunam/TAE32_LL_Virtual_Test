    {
        Kind = LlAssertionKind.RegisterValue,
        InstanceName = instance,
        MemberName = member,
        ExpectedHex = $"0x{expected:X}",
        ExpectedMask = mask,
        RuleSource = LlAssertionRuleSource.FromRegisterDefinition,
        RuleSourceDetail = detail
    };

