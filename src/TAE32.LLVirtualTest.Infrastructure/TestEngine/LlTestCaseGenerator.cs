                        RuleSource = LlAssertionRuleSource.FromRegisterDefinition,
                        RuleSourceDetail = $"位域 {bfName} 写入值"
                    });
                }
            }

            assertions.AddRange(DefaultTimeoutAssertions());
            model.Assertions = assertions;
            model.Notes = sampleMacro is null
                ? $"自动写后校验：参数=0x{paramBits:X}{(isFieldValueStyle ? "（字段值）" : "（寄存器位）")}；断言 {member} & 0x{clearMask:X}=0x{expectedBits:X}。可检出错误 Msk/Pos/RHS。虚拟环境，非真实硬件。"
