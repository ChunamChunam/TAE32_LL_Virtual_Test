using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using TAE32.LLVirtualTest.Core.Models;

namespace TAE32.LLVirtualTest.Infrastructure.TestEngine;

/// <summary>
/// Generates a C harness that includes the real LL header and calls the real inline LL function.
/// Peripheral bases are host-provided RAM images — never MCU absolute addresses on the host.
/// Supports optional prelude calls (e.g. Write then Read) in one run.
/// </summary>
public static class TestHarnessGenerator
{
    public static string Generate(
        string functionName,
        string llHeaderFileName,
        IReadOnlyList<LlTestParameterValue> parameters,
        string? returnType,
        string peripheralInstanceHint,
        string? functionSignature = null,
        IReadOnlyList<LlTestCallStep>? preludeCalls = null)
    {
        parameters = EnsureParameters(parameters, functionSignature, peripheralInstanceHint);
        preludeCalls ??= Array.Empty<LlTestCallStep>();

        var sb = new StringBuilder();
        sb.AppendLine("/* AUTO-GENERATED by TAE32 LL Virtual Test — do not edit SDK */");
        sb.AppendLine("#include <stdint.h>");
        sb.AppendLine("#include <stddef.h>");
        sb.AppendLine();
        sb.AppendLine("#ifndef __GNUC__");
        sb.AppendLine("#define __GNUC__ 4");
        sb.AppendLine("#endif");
        sb.AppendLine("#ifndef __STATIC_INLINE");
        sb.AppendLine("#define __STATIC_INLINE static inline");
        sb.AppendLine("#endif");
        sb.AppendLine("#ifndef __STATIC_FORCEINLINE");
        sb.AppendLine("#define __STATIC_FORCEINLINE static inline");
        sb.AppendLine("#endif");
        sb.AppendLine("#ifndef __INLINE");
        sb.AppendLine("#define __INLINE inline");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("typedef struct {");
        sb.AppendLine("  uint8_t* base;");
        sb.AppendLine("  uint32_t size;");
        sb.AppendLine("} tae32_peri_img;");
        sb.AppendLine();
        sb.AppendLine($"#include \"{Escape(llHeaderFileName)}\"");
        sb.AppendLine();
        sb.AppendLine("#if defined(_WIN32)");
        sb.AppendLine("#define TAE32_EXPORT __declspec(dllexport)");
        sb.AppendLine("#else");
        sb.AppendLine("#define TAE32_EXPORT __attribute__((visibility(\"default\")))");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("TAE32_EXPORT const char* tae32_harness_function(void) { return \"" + Escape(functionName) + "\"; }");
        sb.AppendLine();

        // Flatten all scalar arg fields from prelude + main (unique names).
        var allSteps = preludeCalls
            .Select((s, i) => (Step: s, Prefix: $"p{i}_"))
            .Append((Step: new LlTestCallStep { FunctionName = functionName, Parameters = parameters.ToList() }, Prefix: "m_"))
            .ToList();

        sb.AppendLine("typedef struct {");
        var fieldNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (step, prefix) in allSteps)
        {
            foreach (var p in step.Parameters)
            {
                if (IsPeripheralTypeDefPointer(p)) continue;
                if (IsPointerType(p.Type) && !IsConstCharPointer(p.Type)) continue;
                var fname = Sanitize(prefix + p.Name);
                if (fieldNames.Add(fname))
                    sb.AppendLine($"  uint32_t {fname};");
            }
        }
        sb.AppendLine("  uint32_t _pad;");
        sb.AppendLine("} tae32_args;");
        sb.AppendLine();

        sb.AppendLine("TAE32_EXPORT int tae32_run(tae32_peri_img* peri, const tae32_args* args, uint32_t* out_ret)");
        sb.AppendLine("{");
        sb.AppendLine("  if (peri == NULL || peri->base == NULL || args == NULL) return -1;");

        // Resolve peri typedef from first TypeDef* across steps.
        var periParam = allSteps.SelectMany(x => x.Step.Parameters).FirstOrDefault(IsPeripheralTypeDefPointer);
        if (periParam is not null)
        {
            var typedefName = ExtractTypeDefName(periParam.Type);
            sb.AppendLine($"  {typedefName}* PERIx = ({typedefName}*)peri->base;");
        }

        // Prelude calls (void expected)
        foreach (var (step, prefix) in allSteps.Where(x => x.Prefix != "m_"))
        {
            var argsList = BuildCallArgs(step.Parameters, prefix, periParam is not null);
            if (argsList is null)
            {
                sb.AppendLine($"  /* unsupported pointer in prelude {step.FunctionName} */");
                sb.AppendLine("  return -2;");
                sb.AppendLine("}");
                return sb.ToString();
            }
            sb.AppendLine($"  {step.FunctionName}({string.Join(", ", argsList)});");
        }

        // Main call
        var mainArgs = BuildCallArgs(parameters, "m_", periParam is not null);
        if (mainArgs is null)
        {
            sb.AppendLine("  /* unsupported pointer in main */");
            sb.AppendLine("  return -2;");
            sb.AppendLine("}");
            return sb.ToString();
        }

        var isVoid = string.IsNullOrWhiteSpace(returnType)
                     || returnType.Contains("void", StringComparison.OrdinalIgnoreCase);
        if (isVoid)
        {
            sb.AppendLine($"  {functionName}({string.Join(", ", mainArgs)});");
            sb.AppendLine("  if (out_ret) *out_ret = 0;");
        }
        else
        {
            sb.AppendLine($"  uint32_t __rv = (uint32_t){functionName}({string.Join(", ", mainArgs)});");
            sb.AppendLine("  if (out_ret) *out_ret = __rv;");
        }

        sb.AppendLine("  return 0;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"/* peripheral hint: {Escape(peripheralInstanceHint)} */");
        return sb.ToString();
    }

    private static List<string>? BuildCallArgs(
        IReadOnlyList<LlTestParameterValue> parameters, string prefix, bool hasPeri)
    {
        var callArgs = new List<string>();
        foreach (var p in parameters)
        {
            if (IsPeripheralTypeDefPointer(p))
            {
                if (!hasPeri) return null;
                callArgs.Add("PERIx");
                continue;
            }
            if (IsPointerType(p.Type) && !IsConstCharPointer(p.Type))
                return null;
            callArgs.Add($"(uint32_t)args->{Sanitize(prefix + p.Name)}");
        }
        return callArgs;
    }

    public static IReadOnlyList<LlTestParameterValue> EnsureParameters(
        IReadOnlyList<LlTestParameterValue>? parameters,
        string? functionSignature,
        string? peripheralInstanceHint)
    {
        if (parameters is { Count: > 0 })
            return parameters.ToList();

        var parsed = ParseParametersFromSignature(functionSignature);
        if (parsed.Count == 0) return Array.Empty<LlTestParameterValue>();

        var hint = string.IsNullOrWhiteSpace(peripheralInstanceHint) ? "PERI" : peripheralInstanceHint.Trim();
        foreach (var p in parsed)
        {
            if (IsPeripheralTypeDefPointer(p) && (string.IsNullOrWhiteSpace(p.ValueExpression) || p.ValueExpression == "0"))
                p.ValueExpression = hint;
        }
        return parsed;
    }

    public static List<LlTestParameterValue> ParseParametersFromSignature(string? signature)
    {
        var list = new List<LlTestParameterValue>();
        if (string.IsNullOrWhiteSpace(signature)) return list;
        var open = signature.IndexOf('(');
        var close = signature.LastIndexOf(')');
        if (open < 0 || close <= open) return list;
        var inside = signature[(open + 1)..close].Trim();
        if (string.IsNullOrWhiteSpace(inside) || inside == "void") return list;

        foreach (var part in SplitArgs(inside))
        {
            var token = part.Trim();
            if (token.Length == 0) continue;
            var m = Regex.Match(token, @"^(?<type>.+?)\s*(?<name>[A-Za-z_][A-Za-z0-9_]*)\s*$");
            if (!m.Success)
            {
                list.Add(new LlTestParameterValue
                {
                    Name = "arg" + list.Count,
                    Type = token,
                    ValueExpression = "0",
                    RuleSource = "FromSignature"
                });
                continue;
            }

            list.Add(new LlTestParameterValue
            {
                Name = m.Groups["name"].Value,
                Type = m.Groups["type"].Value.Trim(),
                ValueExpression = "0",
                RuleSource = "FromSignature"
            });
        }
        return list;
    }

    public static Dictionary<string, uint> BuildArgsBlob(
        IReadOnlyList<LlTestParameterValue> parameters,
        IReadOnlyList<LlTestCallStep>? prelude = null)
    {
        var dict = new Dictionary<string, uint>(StringComparer.OrdinalIgnoreCase);
        prelude ??= Array.Empty<LlTestCallStep>();
        for (var i = 0; i < prelude.Count; i++)
        {
            foreach (var p in prelude[i].Parameters)
            {
                if (IsPeripheralTypeDefPointer(p)) continue;
                dict[Sanitize($"p{i}_" + p.Name)] = ParseUIntExpression(p.ValueExpression);
            }
        }
        foreach (var p in parameters)
        {
            if (IsPeripheralTypeDefPointer(p)) continue;
            dict[Sanitize("m_" + p.Name)] = ParseUIntExpression(p.ValueExpression);
        }
        return dict;
    }

    public static uint ParseUIntExpression(string? expr)
    {
        if (string.IsNullOrWhiteSpace(expr)) return 0;
        var s = expr.Trim();
        s = RegexTrimSuffix(s);
        if (s.StartsWith("0x", StringComparison.OrdinalIgnoreCase)
            && uint.TryParse(s.AsSpan(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hex))
            return hex;
        if (uint.TryParse(s, NumberStyles.Integer, CultureInfo.InvariantCulture, out var dec))
            return dec;
        return 0;
    }

    public static bool IsPeripheralTypeDefPointer(LlTestParameterValue p)
        => p.Type.Contains("TypeDef", StringComparison.OrdinalIgnoreCase) && p.Type.Contains('*');

    private static string ExtractTypeDefName(string type)
    {
        var t = StripQualifiers(type).Replace("*", "").Trim();
        var m = Regex.Match(t, @"([A-Za-z_][A-Za-z0-9_]*_TypeDef)");
        return m.Success ? m.Groups[1].Value : t.Split(' ', StringSplitOptions.RemoveEmptyEntries).Last();
    }

    private static IEnumerable<string> SplitArgs(string inside)
    {
        var depth = 0;
        var start = 0;
        for (var i = 0; i < inside.Length; i++)
        {
            var ch = inside[i];
            if (ch is '(' or '[' or '<') depth++;
            else if (ch is ')' or ']' or '>') depth = Math.Max(0, depth - 1);
            else if (ch == ',' && depth == 0)
            {
                yield return inside[start..i];
                start = i + 1;
            }
        }
        yield return inside[start..];
    }

    private static string RegexTrimSuffix(string s)
    {
        if (s.EndsWith("UL", StringComparison.OrdinalIgnoreCase)) return s[..^2];
        if (s.EndsWith("U", StringComparison.OrdinalIgnoreCase)) return s[..^1];
        return s;
    }

    private static bool IsPointerType(string type) => type.Contains('*');
    private static bool IsConstCharPointer(string type)
        => type.Contains("char", StringComparison.OrdinalIgnoreCase) && type.Contains('*');

    private static string StripQualifiers(string type)
        => type.Replace("const", "", StringComparison.OrdinalIgnoreCase)
            .Replace("volatile", "", StringComparison.OrdinalIgnoreCase)
            .Trim();

    private static string Sanitize(string name)
    {
        var sb = new StringBuilder();
        foreach (var ch in name)
            sb.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, 'p');
        return sb.ToString();
    }

    private static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
