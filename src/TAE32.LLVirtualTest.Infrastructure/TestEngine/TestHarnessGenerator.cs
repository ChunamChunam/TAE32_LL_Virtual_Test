using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using TAE32.LLVirtualTest.Core.Models;

namespace TAE32.LLVirtualTest.Infrastructure.TestEngine;

/// <summary>
/// Generates a C harness that includes the real LL header and calls the real inline LL function.
/// Peripheral bases are host-provided RAM images — never MCU absolute addresses on the host.
/// Supports optional prelude calls (e.g. Write then Read) in one run.
/// </summary>
public static class TestHarnessGenerator
{
    public static string Generate(
        string functionName,
        string llHeaderFileName,
        IReadOnlyList<LlTestParameterValue> parameters,
        string? returnType,
        string peripheralInstanceHint,
        string? functionSignature = null,
        IReadOnlyList<LlTestCallStep>? preludeCalls = null,
        string? deviceHeaderFileName = null)
    {
        parameters = EnsureParameters(parameters, functionSignature, peripheralInstanceHint);
        preludeCalls ??= Array.Empty<LlTestCallStep>();
        deviceHeaderFileName = ResolveDeviceHeaderFileName(deviceHeaderFileName, llHeaderFileName);

        var sb = new StringBuilder();
        sb.AppendLine("/* AUTO-GENERATED by TAE32 LL Virtual Test — do not edit SDK */");
        sb.AppendLine("#include <stdint.h>");
        sb.AppendLine("#include <stddef.h>");
        sb.AppendLine();
        sb.AppendLine("#ifndef __GNUC__");
        sb.AppendLine("#define __GNUC__ 4");
        sb.AppendLine("#endif");
        sb.AppendLine("#ifndef __STATIC_INLINE");
        sb.AppendLine("#define __STATIC_INLINE static inline");
        sb.AppendLine("#endif");
        sb.AppendLine("#ifndef __STATIC_FORCEINLINE");
        sb.AppendLine("#define __STATIC_FORCEINLINE static inline");
        sb.AppendLine("#endif");
        sb.AppendLine("#ifndef __INLINE");
        sb.AppendLine("#define __INLINE inline");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("typedef struct {");
        sb.AppendLine("  uint8_t* base;");
        sb.AppendLine("  uint32_t size;");
        sb.AppendLine("} tae32_peri_img;");
        sb.AppendLine();
        sb.AppendLine("#include \"tae32_ll_host_scs_buf.h\"");
        sb.AppendLine($"#include \"{Escape(deviceHeaderFileName)}\"");
        sb.AppendLine("#include \"tae32_ll_host_scs_remap.h\"");
        sb.AppendLine("#include \"tae32_ll_host_scs_remap_tail.h\"");
        sb.AppendLine("#include \"tae32_ll_host_cmsis_override.h\"");
        sb.AppendLine("#include \"tae32_ll_host_peri_glob.h\"");
        sb.AppendLine("#include \"tae32_ll_host_eflash.h\"");
        sb.AppendLine("#include \"tae32_ll_host_shim.h\"");
        // Host x64: provide portable __CLZ/__RBIT before LL headers expand POSITION_VAL(mask).
        sb.AppendLine("static inline uint32_t tae32_host_rbit(uint32_t v)");
        sb.AppendLine("{");
        sb.AppendLine("  v = ((v & 0x55555555u) << 1) | ((v >> 1) & 0x55555555u);");
        sb.AppendLine("  v = ((v & 0x33333333u) << 2) | ((v >> 2) & 0x33333333u);");
        sb.AppendLine("  v = ((v & 0x0F0F0F0Fu) << 4) | ((v >> 4) & 0x0F0F0F0Fu);");
        sb.AppendLine("  v = ((v & 0x00FF00FFu) << 8) | ((v >> 8) & 0x00FF00FFu);");
        sb.AppendLine("  return (v << 16) | (v >> 16);");
        sb.AppendLine("}");
        sb.AppendLine("static inline uint32_t tae32_host_clz(uint32_t x)");
        sb.AppendLine("{");
        sb.AppendLine("  uint32_t n = 0u;");
        sb.AppendLine("  if (x == 0u) return 32u;");
        sb.AppendLine("  if ((x & 0xFFFF0000u) == 0u) { n += 16u; x <<= 16; }");
        sb.AppendLine("  if ((x & 0xFF000000u) == 0u) { n += 8u; x <<= 8; }");
        sb.AppendLine("  if ((x & 0xF0000000u) == 0u) { n += 4u; x <<= 4; }");
        sb.AppendLine("  if ((x & 0xC0000000u) == 0u) { n += 2u; x <<= 2; }");
        sb.AppendLine("  if ((x & 0x80000000u) == 0u) { n += 1u; }");
        sb.AppendLine("  return n;");
        sb.AppendLine("}");
        sb.AppendLine("#undef __RBIT");
        sb.AppendLine("#undef __CLZ");
        sb.AppendLine("#define __RBIT(x) tae32_host_rbit((uint32_t)(x))");
        sb.AppendLine("#define __CLZ(x) tae32_host_clz((uint32_t)(x))");
        sb.AppendLine($"#include \"{Escape(llHeaderFileName)}\"");
        sb.AppendLine();
        sb.AppendLine("#if defined(_WIN32)");
        sb.AppendLine("#define TAE32_EXPORT __declspec(dllexport)");
        sb.AppendLine("#else");
        sb.AppendLine("#define TAE32_EXPORT __attribute__((visibility(\"default\")))");
        sb.AppendLine("#endif");
        sb.AppendLine();
        sb.AppendLine("TAE32_EXPORT const char* tae32_harness_function(void) { return \"" + Escape(functionName) + "\"; }");
        sb.AppendLine();

        // Flatten all scalar arg fields from prelude + main (unique names).
        var allSteps = preludeCalls
            .Select((s, i) => (Step: s, Prefix: $"p{i}_"))
            .Append((Step: new LlTestCallStep { FunctionName = functionName, Parameters = parameters.ToList() }, Prefix: "m_"))
            .ToList();

        sb.AppendLine("typedef struct {");
        var fieldNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (step, prefix) in allSteps)
        {
            foreach (var p in step.Parameters)
            {
                if (IsPeripheralTypeDefPointer(p)) continue;
                if (IsHostPointerBuffer(p)) continue;
                var fname = Sanitize(prefix + p.Name);
                if (fieldNames.Add(fname))
                    sb.AppendLine($"  uint32_t {fname};");
            }
        }
        sb.AppendLine("  uint32_t _pad;");
        sb.AppendLine("} tae32_args;");
        sb.AppendLine();

        sb.AppendLine("TAE32_EXPORT int tae32_run(tae32_peri_img* peri, const tae32_args* args, uint32_t* out_ret)");
        sb.AppendLine("{");
        sb.AppendLine("  if (peri == NULL || peri->base == NULL || args == NULL) return -1;");
        sb.AppendLine("  tae32_host_peri_load(peri->base, peri->size);");

        // Resolve peri typedef from first TypeDef* across steps.
        var periParam = allSteps.SelectMany(x => x.Step.Parameters).FirstOrDefault(IsPeripheralTypeDefPointer);
        if (periParam is not null)
        {
            var typedefName = ExtractTypeDefName(periParam.Type);
            sb.AppendLine($"  {typedefName}* PERIx = ({typedefName}*)tae32_host_peri_image;");
        }
        else
        {
            EmitHostPeripheralTypedef(sb, llHeaderFileName);
        }

        EmitHostPointerBuffers(sb, allSteps);

        // Prelude calls (void expected)
        foreach (var (step, prefix) in allSteps.Where(x => x.Prefix != "m_"))
        {
            var argsList = BuildCallArgs(step.Parameters, prefix, periParam is not null);
            if (argsList is null)
            {
                sb.AppendLine($"  /* unsupported pointer in prelude {step.FunctionName} */");
                sb.AppendLine("  return -2;");
                sb.AppendLine("}");
                return sb.ToString();
            }
            sb.AppendLine($"  {step.FunctionName}({string.Join(", ", argsList)});");
            // Host RAM has no BSR hardware side-effect; mirror before a later Read* sees DOR.
            EmitHostGpioBsrToDorMirror(sb, periParam);
        }

        // Main call
        var mainArgs = BuildCallArgs(parameters, "m_", periParam is not null);
        if (mainArgs is null)
        {
            sb.AppendLine("  /* unsupported pointer in main */");
            sb.AppendLine("  return -2;");
            sb.AppendLine("}");
            return sb.ToString();
        }

        if (TryEmitHostBusyPollAck(sb, functionName))
        {
            /* body emitted */
        }
        else
        {
            var isVoid = string.IsNullOrWhiteSpace(returnType)
                         || returnType.Contains("void", StringComparison.OrdinalIgnoreCase);
            if (isVoid)
            {
                sb.AppendLine($"  {functionName}({string.Join(", ", mainArgs)});");
                EmitHostGpioBsrToDorMirror(sb, periParam);
                // Insert*(uint32_t* Addr): mirror first host word so ReturnValue can assert RMW.
                var hostSym = parameters
                    .Where(IsHostPointerBuffer)
                    .Select(p => HostPointerSymbol("m_", p.Name))
                    .FirstOrDefault();
                if (hostSym is not null)
                    sb.AppendLine($"  if (out_ret) *out_ret = (uint32_t){hostSym}[0];");
                else
                    sb.AppendLine("  if (out_ret) *out_ret = 0;");
            }
            else if (TryEmitHostBufferAddressOffset(sb, functionName, mainArgs))
            {
                /* LL returns truncated host ptr on x64; remap to peri offsetof for assert. */
            }
            else
            {
                sb.AppendLine($"  uint32_t __rv = (uint32_t){functionName}({string.Join(", ", mainArgs)});");
                sb.AppendLine("  if (out_ret) *out_ret = __rv;");
            }
        }

        sb.AppendLine("  tae32_host_peri_store(peri->base, peri->size);");
        sb.AppendLine("  return 0;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"/* peripheral hint: {Escape(peripheralInstanceHint)} */");
        return sb.ToString();
    }

    private static List<string>? BuildCallArgs(
        IReadOnlyList<LlTestParameterValue> parameters, string prefix, bool hasPeri)
    {
        var callArgs = new List<string>();
        foreach (var p in parameters)
        {
            if (IsPeripheralTypeDefPointer(p))
            {
                if (!hasPeri) return null;
                callArgs.Add("PERIx");
                continue;
            }
            if (IsHostPointerBuffer(p))
            {
                callArgs.Add(HostPointerSymbol(prefix, p.Name));
                continue;
            }
            if (p.Type.Contains("IRQn", StringComparison.OrdinalIgnoreCase))
            {
                callArgs.Add($"(IRQn_Type)args->{Sanitize(prefix + p.Name)}");
                continue;
            }
            callArgs.Add($"(uint32_t)args->{Sanitize(prefix + p.Name)}");
        }
        return callArgs;
    }

    public static IReadOnlyList<LlTestParameterValue> EnsureParameters(
        IReadOnlyList<LlTestParameterValue>? parameters,
        string? functionSignature,
        string? peripheralInstanceHint,
        string? functionName = null)
    {
        List<LlTestParameterValue> list;
        if (parameters is { Count: > 0 })
        {
            list = parameters.ToList();
        }
        else
        {
            var parsed = ParseParametersFromSignature(functionSignature);
            if (parsed.Count == 0) return Array.Empty<LlTestParameterValue>();
            list = parsed;
        }

        var hint = string.IsNullOrWhiteSpace(peripheralInstanceHint) ? "PERI" : peripheralInstanceHint.Trim();
        foreach (var p in list)
        {
            if (IsPeripheralTypeDefPointer(p) && (string.IsNullOrWhiteSpace(p.ValueExpression) || p.ValueExpression == "0"))
                p.ValueExpression = hint;
        }

        // Timeout-only drafts often leave Mode/Div=0 → MODIFY_REG no-op → empty deltas / Skipped.
        ApplySetterNonZeroDefaults(functionName ?? InferFunctionName(functionSignature), list);
        return list;
    }

    private static string? InferFunctionName(string? signature)
    {
        if (string.IsNullOrWhiteSpace(signature)) return null;
        var m = Regex.Match(signature, @"\b(LL_[A-Za-z0-9_]+)\s*\(");
        return m.Success ? m.Groups[1].Value : null;
    }

    private static void ApplySetterNonZeroDefaults(string? functionName, List<LlTestParameterValue> list)
    {
        if (string.IsNullOrWhiteSpace(functionName)) return;
        var isSetter = functionName.Contains("Set", StringComparison.OrdinalIgnoreCase)
                       || functionName.Contains("Write", StringComparison.OrdinalIgnoreCase)
                       || functionName.Contains("Config", StringComparison.OrdinalIgnoreCase);
        if (!isSetter) return;

        foreach (var p in list)
        {
            if (!string.Equals(p.ValueExpression, "0", StringComparison.Ordinal)) continue;
            if (IsPeripheralTypeDefPointer(p) || IsHostPointerBuffer(p)) continue;
            if (p.Name.Equals("Mode", StringComparison.OrdinalIgnoreCase)
                || p.Name.Equals("Div", StringComparison.OrdinalIgnoreCase)
                || p.Name.Equals("Divider", StringComparison.OrdinalIgnoreCase)
                || p.Name.Equals("Value", StringComparison.OrdinalIgnoreCase)
                || p.Name.Equals("State", StringComparison.OrdinalIgnoreCase)
                || p.Name.Contains("Prescaler", StringComparison.OrdinalIgnoreCase)
                || p.Name.Contains("Prescl", StringComparison.OrdinalIgnoreCase))
            {
                p.ValueExpression = "1";
            }
        }
    }

    public static List<LlTestParameterValue> ParseParametersFromSignature(string? signature)
    {
        var list = new List<LlTestParameterValue>();
        if (string.IsNullOrWhiteSpace(signature)) return list;
        var open = signature.IndexOf('(');
        var close = signature.LastIndexOf(')');
        if (open < 0 || close <= open) return list;
        var inside = signature[(open + 1)..close].Trim();
        if (string.IsNullOrWhiteSpace(inside) || inside == "void") return list;

        foreach (var part in SplitArgs(inside))
        {
            var token = part.Trim();
            if (token.Length == 0) continue;
            var m = Regex.Match(token, @"^(?<type>.+?)\s*(?<name>[A-Za-z_][A-Za-z0-9_]*)\s*$");
            if (!m.Success)
            {
                list.Add(new LlTestParameterValue
                {
                    Name = "arg" + list.Count,
                    Type = token,
                    ValueExpression = "0",
                    RuleSource = "FromSignature"
                });
                continue;
            }

            list.Add(new LlTestParameterValue
            {
                Name = m.Groups["name"].Value,
                Type = m.Groups["type"].Value.Trim(),
                ValueExpression = "0",
                RuleSource = "FromSignature"
            });
        }
        return list;
    }

    public static Dictionary<string, uint> BuildArgsBlob(
        IReadOnlyList<LlTestParameterValue> parameters,
        IReadOnlyList<LlTestCallStep>? prelude = null)
    {
        var dict = new Dictionary<string, uint>(StringComparer.OrdinalIgnoreCase);
        prelude ??= Array.Empty<LlTestCallStep>();
        for (var i = 0; i < prelude.Count; i++)
        {
            foreach (var p in prelude[i].Parameters)
            {
                if (IsPeripheralTypeDefPointer(p)) continue;
                dict[Sanitize($"p{i}_" + p.Name)] = ParseUIntExpression(p.ValueExpression);
            }
        }
        foreach (var p in parameters)
        {
            if (IsPeripheralTypeDefPointer(p)) continue;
            dict[Sanitize("m_" + p.Name)] = ParseUIntExpression(p.ValueExpression);
        }
        return dict;
    }

    /// <summary>Argument uint32 values in the same order as the generated <c>tae32_args</c> struct fields.</summary>
    public static IReadOnlyList<uint> BuildArgsValuesInHarnessOrder(
        IReadOnlyList<LlTestParameterValue> parameters,
        IReadOnlyList<LlTestCallStep>? prelude = null)
    {
        var list = new List<uint>();
        prelude ??= Array.Empty<LlTestCallStep>();
        for (var i = 0; i < prelude.Count; i++)
        {
            foreach (var p in prelude[i].Parameters)
            {
                // Must match tae32_args field layout: peri TypeDef* and host_* buffers are not fields.
                if (IsPeripheralTypeDefPointer(p) || IsHostPointerBuffer(p)) continue;
                list.Add(ParseUIntExpression(p.ValueExpression));
            }
        }
        foreach (var p in parameters)
        {
            if (IsPeripheralTypeDefPointer(p) || IsHostPointerBuffer(p)) continue;
            list.Add(ParseUIntExpression(p.ValueExpression));
        }
        return list;
    }

    public static uint ParseUIntExpression(string? expr)
    {
        if (string.IsNullOrWhiteSpace(expr)) return 0;
        var s = expr.Trim();
        // Strip accidental C comments (e.g. "0x100 /* MACRO */") so harness args never collapse to 0.
        var block = s.IndexOf("/*", StringComparison.Ordinal);
        if (block >= 0) s = s[..block].Trim();
        var line = s.IndexOf("//", StringComparison.Ordinal);
        if (line >= 0) s = s[..line].Trim();
        s = RegexTrimSuffix(s);
        if (s.StartsWith("0x", StringComparison.OrdinalIgnoreCase)
            && uint.TryParse(s.AsSpan(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hex))
            return hex;
        if (uint.TryParse(s, NumberStyles.Integer, CultureInfo.InvariantCulture, out var dec))
            return dec;
        return 0;
    }

    public static bool IsPeripheralTypeDefPointer(LlTestParameterValue p)
        => p.Type.Contains("TypeDef", StringComparison.OrdinalIgnoreCase) && p.Type.Contains('*');

    internal static bool IsHostPointerBuffer(LlTestParameterValue p)
        => IsPointerType(p.Type) && !IsPeripheralTypeDefPointer(p) && !IsConstCharPointer(p.Type);

    private static string HostPointerSymbol(string prefix, string paramName)
        => "host_ptr_" + Sanitize(prefix + paramName);

    private static void EmitHostPointerBuffers(
        StringBuilder sb,
        List<(LlTestCallStep Step, string Prefix)> allSteps)
    {
        var emitted = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (step, prefix) in allSteps)
        {
            foreach (var p in step.Parameters)
            {
                if (!IsHostPointerBuffer(p)) continue;
                var sym = HostPointerSymbol(prefix, p.Name);
                if (!emitted.Add(sym)) continue;
                if (p.Type.Contains("uint8", StringComparison.OrdinalIgnoreCase))
                    sb.AppendLine($"  uint8_t {sym}[64] = {{0}};");
                else
                    sb.AppendLine($"  uint32_t {sym}[16] = {{0}};");
            }
        }
    }

    /// <summary>
    /// Get*DataBufferAddress returns (uint32_t)&amp;peri-&gt;BUF[0]. On host x64 that truncates;
    /// emit offsetof(PERIx, BUFx) after invoking the LL for coverage.
    /// </summary>
    private static bool TryEmitHostBufferAddressOffset(
        StringBuilder sb, string functionName, List<string> mainArgs)
    {
        if (functionName.Contains("GetSysDMADataAddr", StringComparison.OrdinalIgnoreCase))
        {
            if (periParamMissing(mainArgs))
                return false;
            sb.AppendLine($"  (void){functionName}({string.Join(", ", mainArgs)});");
            sb.AppendLine("  /* host: LL returns uint32_t* (x64 truncates); assert peri offsetof */");
            if (functionName.Contains("_MST_", StringComparison.OrdinalIgnoreCase))
            {
                sb.AppendLine(
                    "  if (out_ret) *out_ret = (uint32_t)((uintptr_t)&PERIx->Master.MDMADR - (uintptr_t)PERIx);");
            }
            else
            {
                sb.AppendLine(
                    "  if (out_ret) *out_ret = (uint32_t)((uintptr_t)&PERIx->PWM[((uint32_t)args->m_Pwmx) % LL_HRPWM_PWMx_NUMS].REG.DMADR - (uintptr_t)PERIx);");
            }

            return true;
        }

        if (!functionName.Contains("GetDataBufferAddress", StringComparison.OrdinalIgnoreCase))
            return false;

        string? member = null;
        if (functionName.Contains("_PRB_", StringComparison.OrdinalIgnoreCase))
            member = "RBUFDT";
        else if (functionName.Contains("_SRB_", StringComparison.OrdinalIgnoreCase))
            member = "SBUFDT";
        else if (functionName.Contains("_ETB_", StringComparison.OrdinalIgnoreCase))
            member = "EBUFDT";
        if (member is null || periParamMissing(mainArgs))
            return false;

        sb.AppendLine($"  (void){functionName}({string.Join(", ", mainArgs)});");
        sb.AppendLine($"  /* host: LL casts &{member}[0] to uint32_t (MCU ABI); assert peri offsetof */");
        sb.AppendLine($"  if (out_ret) *out_ret = (uint32_t)((uintptr_t)&PERIx->{member}[0] - (uintptr_t)PERIx);");
        return true;

        static bool periParamMissing(List<string> args)
            => args.Count == 0 || !args.Exists(a => a.Contains("PERIx", StringComparison.Ordinal));
    }

    /// <summary>SDK functions that spin on hardware-ready bits: host ack without infinite wait.</summary>
    private static bool TryEmitHostBusyPollAck(StringBuilder sb, string functionName)
    {
        switch (functionName)
        {
            case "LL_CAN_ETB_WaitBufferRelease":
                EmitCanWaitAck(sb, "CAN0_CTRL_EREL_Msk", "CAN0_CTRL_EREL_Pos");
                return true;
            case "LL_CAN_SRB_WaitBufferRelease":
                EmitCanWaitAck(sb, "CAN0_CTRL_SREL_Msk", "CAN0_CTRL_SREL_Pos");
                return true;
            case "LL_CAN_PRB_WaitBufferRelease":
                EmitCanWaitAck(sb, "CAN0_CTRL_RREL_Msk", "CAN0_CTRL_RREL_Pos");
                return true;
            case "LL_HRPWM_MST_SetCounter":
                sb.AppendLine("  WRITE_REG(PERIx->Master.MCNTR, HRPWM_MST_MCNTR_CNTWR_Msk | ((uint32_t)args->m_Cnt & HRPWM_MST_MCNTR_MCNT_Val));");
                sb.AppendLine("  CLEAR_BIT(PERIx->Master.MCNTR, HRPWM_MST_MCNTR_CNTWR_Msk);");
                sb.AppendLine("  if (out_ret) *out_ret = 0;");
                return true;
            case "LL_HRPWM_SLV_SetCounter":
                sb.AppendLine("  WRITE_REG(PERIx->PWM[((uint32_t)args->m_Pwmx) % LL_HRPWM_PWMx_NUMS].REG.CNTR,");
                sb.AppendLine("      HRPWM_SLV0_CNTR_CNTWR_Msk | ((uint32_t)args->m_Cnt & HRPWM_SLV0_CNTR_CNT_Val));");
                sb.AppendLine("  CLEAR_BIT(PERIx->PWM[((uint32_t)args->m_Pwmx) % LL_HRPWM_PWMx_NUMS].REG.CNTR, HRPWM_SLV0_CNTR_CNTWR_Msk);");
                sb.AppendLine("  if (out_ret) *out_ret = 0;");
                return true;
            case "LL_Delay_NoISR":
                sb.AppendLine("  /* host: satisfy COUNTFLAG wait loop (no real time) */");
                sb.AppendLine("  {");
                sb.AppendLine("    uint32_t ms = args->m_Milliseconds ? args->m_Milliseconds : 1u;");
                sb.AppendLine("    while (ms--) {");
                sb.AppendLine("      SysTick->CTRL |= SysTick_CTRL_COUNTFLAG_Msk;");
                sb.AppendLine("    }");
                sb.AppendLine("  }");
                sb.AppendLine("  if (out_ret) *out_ret = 0;");
                return true;
            case "LL_NVIC_SetPriorityGrouping":
                sb.AppendLine("  LL_NVIC_SetPriorityGrouping((uint32_t)args->m_PriorityGroup);");
                sb.AppendLine("  if (out_ret) *out_ret = LL_NVIC_GetPriorityGrouping();");
                return true;
            case "LL_NVIC_SetPriority":
                sb.AppendLine("  LL_NVIC_SetPriority((IRQn_Type)args->m_IRQn, (uint32_t)args->m_PreemptPriority, (uint32_t)args->m_SubPriority);");
                sb.AppendLine("  if (out_ret) *out_ret = NVIC_GetPriority((IRQn_Type)args->m_IRQn);");
                return true;
            case "LL_InitTick":
                sb.AppendLine("  LL_InitTick((uint32_t)args->m_CPU_Clk_Freq, (uint32_t)args->m_Ticks);");
                sb.AppendLine("  if (out_ret) *out_ret = SysTick->LOAD;");
                return true;
            case "LL_Init1msTick":
                sb.AppendLine("  LL_Init1msTick((uint32_t)args->m_CPU_Clk_Freq);");
                sb.AppendLine("  if (out_ret) *out_ret = SysTick->LOAD;");
                return true;
            default:
                return false;
        }
    }

    private static void EmitCanWaitAck(StringBuilder sb, string mask, string pos)
    {
        sb.AppendLine($"  SET_BIT(PERIx->CTRL, {mask});");
        sb.AppendLine($"  while (READ_BIT_SHIFT(PERIx->CTRL, {mask}, {pos})) {{");
        sb.AppendLine($"    CLEAR_BIT(PERIx->CTRL, {mask});");
        sb.AppendLine("    break; /* host: buffer release ack (virtual CAN) */");
        sb.AppendLine("  }");
        sb.AppendLine("  if (out_ret) *out_ret = 0;");
    }

    /// <summary>
    /// TAE32 GPIO: BSR set/reset does not update DOR on host RAM. Mirror after writes so
    /// subsequent ReadOutputPort / IsOutputPinSet see the correct data-out level.
    /// </summary>
    private static void EmitHostGpioBsrToDorMirror(StringBuilder sb, LlTestParameterValue? periParam)
    {
        if (periParam is null) return;
        var typedefName = ExtractTypeDefName(periParam.Type);
        if (!typedefName.Contains("GPIO", StringComparison.OrdinalIgnoreCase)) return;

        sb.AppendLine("  /* host: BSR→DOR (BSn@0 / BRn@16); real silicon does this in HW */");
        sb.AppendLine("  {");
        sb.AppendLine("    uint32_t __bsr = PERIx->BSR;");
        sb.AppendLine("    uint32_t __dor = PERIx->DOR;");
        sb.AppendLine("    PERIx->DOR = (__dor | (__bsr & 0xFFFFu)) & ~((__bsr >> 16) & 0xFFFFu);");
        sb.AppendLine("  }");
    }

    private static string ExtractTypeDefName(string type)
    {
        var t = StripQualifiers(type).Replace("*", "").Trim();
        var m = Regex.Match(t, @"([A-Za-z_][A-Za-z0-9_]*_TypeDef)");
        return m.Success ? m.Groups[1].Value : t.Split(' ', StringSplitOptions.RemoveEmptyEntries).Last();
    }

    private static IEnumerable<string> SplitArgs(string inside)
    {
        var depth = 0;
        var start = 0;
        for (var i = 0; i < inside.Length; i++)
        {
            var ch = inside[i];
            if (ch is '(' or '[' or '<') depth++;
            else if (ch is ')' or ']' or '>') depth = Math.Max(0, depth - 1);
            else if (ch == ',' && depth == 0)
            {
                yield return inside[start..i];
                start = i + 1;
            }
        }
        yield return inside[start..];
    }

    private static string RegexTrimSuffix(string s)
    {
        if (s.EndsWith("UL", StringComparison.OrdinalIgnoreCase)) return s[..^2];
        if (s.EndsWith("U", StringComparison.OrdinalIgnoreCase)) return s[..^1];
        return s;
    }

    private static bool IsPointerType(string type) => type.Contains('*');
    private static bool IsConstCharPointer(string type)
        => type.Contains("char", StringComparison.OrdinalIgnoreCase) && type.Contains('*');

    private static string StripQualifiers(string type)
        => type.Replace("const", "", StringComparison.OrdinalIgnoreCase)
            .Replace("volatile", "", StringComparison.OrdinalIgnoreCase)
            .Trim();

    /// <summary>
    /// Prefer explicit device header; else derive <c>tae32xxxx.h</c> from LL module header name.
    /// </summary>
    internal static string ResolveDeviceHeaderFileName(string? deviceHeaderFileName, string? llHeaderFileName)
    {
        if (!string.IsNullOrWhiteSpace(deviceHeaderFileName))
            return Path.GetFileName(deviceHeaderFileName);

        var fam = Core.Sdk.SdkSeriesLayout.TryFamilyIdFromLlHeader(llHeaderFileName ?? "");
        if (!string.IsNullOrWhiteSpace(fam))
            return fam + ".h";

        return Core.Sdk.SdkSeriesLayout.FallbackFamilyId + ".h";
    }

    private static string Sanitize(string name)
    {
        var sb = new StringBuilder();
        foreach (var ch in name)
            sb.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, 'p');
        return sb.ToString();
    }

    private static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static void EmitHostPeripheralTypedef(StringBuilder sb, string llHeaderFileName)
    {
        var h = llHeaderFileName.ToLowerInvariant();
        if (h.Contains("sysctrl"))
            sb.AppendLine("  SYSCTRL_TypeDef* PERIx = (SYSCTRL_TypeDef*)tae32_host_peri_image;");
        else if (h.Contains("ll_rcu") || h.Contains("rcu"))
            sb.AppendLine("  RCU_TypeDef* PERIx = (RCU_TypeDef*)tae32_host_peri_image;");
        else if (h.Contains("cortex"))
            sb.AppendLine("  /* CORTEX LL uses CMSIS SCS shadow; peri base unused */");
    }
