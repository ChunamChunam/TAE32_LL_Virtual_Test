namespace TAE32.LLVirtualTest.Core.Entities;

public class LlTestCase
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid SdkProjectId { get; set; }
    public Guid? ChipId { get; set; }
    public Guid? LlFunctionId { get; set; }
    public string Name { get; set; } = string.Empty;
    public string? ChipModelName { get; set; }
    public string? PeripheralName { get; set; }
    public string FunctionName { get; set; } = string.Empty;
    public string? FunctionSignature { get; set; }
    public string? SourceFile { get; set; }
    public string Status { get; set; } = "Draft";
    /// <summary>JSON: parameter name → value expression (from real SDK macros / literals).</summary>
    public string ParametersJson { get; set; } = "{}";
    /// <summary>JSON: initial register values [{instance, member, valueHex}].</summary>
    public string InitialRegistersJson { get; set; } = "[]";
    /// <summary>JSON: assertion specs.</summary>
    public string AssertionsJson { get; set; } = "[]";
    public string? Notes { get; set; }
    public bool IsAutoGenerated { get; set; }
    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;
    public DateTime? UpdatedAtUtc { get; set; }

    public SdkProject? SdkProject { get; set; }
    public Chip? Chip { get; set; }
    public LlFunction? LlFunction { get; set; }
    public ICollection<LlTestRun> Runs { get; set; } = new List<LlTestRun>();
}

public class LlTestRun
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid SdkProjectId { get; set; }
    public Guid LlTestCaseId { get; set; }
    public Guid? VirtualMcuId { get; set; }
    public string Status { get; set; } = "Pending";
    public bool CompileSucceeded { get; set; }
    public bool ExecuteCompleted { get; set; }
    public bool AssertionsPassed { get; set; }
    public bool HardwareBehaviorSimulated { get; set; }
    public string? CompilerPath { get; set; }
    public string? CompileLog { get; set; }
    public string? ExecutionLog { get; set; }
    public string? FailureReason { get; set; }
    public string? ReturnValueText { get; set; }
    public string? AccessTraceJson { get; set; }
    public string? AssertionResultsJson { get; set; }
    public string? StagesJson { get; set; }
    public int DurationMs { get; set; }
    public DateTime StartedAtUtc { get; set; } = DateTime.UtcNow;
    public DateTime? FinishedAtUtc { get; set; }

    public SdkProject? SdkProject { get; set; }
    public LlTestCase? TestCase { get; set; }
}

public class LlCompilerProfile
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid? SdkProjectId { get; set; }
    public string Name { get; set; } = "default";
    public string? ClangPath { get; set; }
    public string ExtraArgs { get; set; } = string.Empty;
    public string ExtraDefines { get; set; } = "TAE32G58xx";
    public string ExtraIncludes { get; set; } = string.Empty;
    public int DefaultTimeoutMs { get; set; } = 10000;
    public DateTime UpdatedAtUtc { get; set; } = DateTime.UtcNow;
}
