# -*- coding: utf-8 -*-
import re
import sqlite3
from collections import Counter

DB = r"d:\Code\12_TAE32_LL_Virtual_Test\Publish\data\tae32_ll_virtual_test.db"


def main() -> None:
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    cur = con.cursor()
    cur.execute(
        """
        WITH latest AS (
          SELECT r.*, c.PeripheralName, c.FunctionName, c.IsAutoGenerated,
            ROW_NUMBER() OVER (PARTITION BY r.LlTestCaseId ORDER BY r.StartedAtUtc DESC) rn
          FROM LlTestRuns r JOIN LlTestCases c ON c.Id = r.LlTestCaseId
        )
        SELECT * FROM latest WHERE rn = 1 AND Status <> 'Passed'
        """
    )
    rows = cur.fetchall()
    n = len(rows)
    prog = Counter()
    case = Counter()
    peri = Counter()
    compile_syms = Counter()

    for row in rows:
        reason = row["FailureReason"] or ""
        st = row["Status"]
        if "编译失败" in reason or (st == "Error" and row["CompileSucceeded"] == 0):
            prog["compile"] += 1
            for m in re.findall(r"undefined symbol: (\w+)", reason):
                compile_syms[m] += 1
        elif re.search(r"AccessViolation|-1073741819|宿主执行故障", reason):
            prog["host_ave"] += 1
        elif "divide by zero" in reason.lower():
            prog["engine_params"] += 1
        elif "寄存器" in reason:
            case["assert_register"] += 1
        elif "返回值" in reason:
            case["assert_return"] += 1
        elif st == "Error":
            prog["other_exec"] += 1
        else:
            case["other_failed"] += 1
        peri[(row["PeripheralName"], st)] += 1

    print("=== 最新一次运行：非 Passed ===", n)
    print("引擎/宿主:", sum(prog.values()))
    for k, v in prog.most_common():
        print(f"  {k}: {v}")
    print("用例/虚拟模型:", sum(case.values()))
    for k, v in case.most_common():
        print(f"  {k}: {v}")
    print("外设×状态 Top:")
    for (p, st), v in peri.most_common(12):
        print(f"  {p} / {st}: {v}")
    if compile_syms:
        print("编译 undefined symbol Top:")
        for sym, v in compile_syms.most_common(8):
            print(f"  {sym}: {v}")
    con.close()


if __name__ == "__main__":
    main()
