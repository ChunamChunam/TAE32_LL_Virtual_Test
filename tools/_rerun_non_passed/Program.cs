using System.Diagnostics;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using TAE32.LLVirtualTest.Core.Entities;
using TAE32.LLVirtualTest.Core.Enums;
using TAE32.LLVirtualTest.Core.Interfaces;
using TAE32.LLVirtualTest.Infrastructure;
using TAE32.LLVirtualTest.Infrastructure.Data;
using TAE32.LLVirtualTest.Infrastructure.TestEngine;

static string FindWorkspaceRoot()
{
    var dir = AppContext.BaseDirectory;
    for (var i = 0; i < 10; i++)
    {
        if (File.Exists(Path.Combine(dir, "TAE32.LLVirtualTest.sln")))
            return dir;
        dir = Path.GetDirectoryName(dir) ?? dir;
    }

    return Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", ".."));
}

var workspaceRoot = FindWorkspaceRoot();
var defaultDb = Path.Combine(workspaceRoot, "Publish", "data", "tae32_ll_virtual_test.db");
var dbPath = args.FirstOrDefault(a => !a.StartsWith('-')) ?? defaultDb;
if (args.Contains("--db") && Array.IndexOf(args, "--db") + 1 < args.Length)
    dbPath = args[Array.IndexOf(args, "--db") + 1];

if (!File.Exists(dbPath))
{
    Console.Error.WriteLine("数据库不存在: " + dbPath);
    return 1;
}

var sdkRoot = Path.Combine(workspaceRoot, "SDKContent", "Tai-Action.TAE32G58xx_DFP.2.0.0 ReleaseV2.0.0");

Console.WriteLine("DB: " + dbPath);
Console.WriteLine("SDK: " + sdkRoot);

var services = new ServiceCollection();
services.AddLogging();
services.AddInfrastructure(dbPath);
var sp = services.BuildServiceProvider();
var dbFactory = sp.GetRequiredService<IDbContextFactory<AppDbContext>>();
var store = sp.GetRequiredService<ILlTestCaseStore>();
var engine = sp.GetRequiredService<ILLTestEngine>();

await using (var db = await dbFactory.CreateDbContextAsync())
{
    var project = await db.SdkProjects.AsNoTracking().FirstAsync();
    if (!Directory.Exists(project.SdkRootPath) && Directory.Exists(sdkRoot))
    {
        var entity = await db.SdkProjects.FirstAsync(x => x.Id == project.Id);
        entity.SdkRootPath = sdkRoot;
        await db.SaveChangesAsync();
        Console.WriteLine("已修正 SdkRootPath → " + sdkRoot);
    }
    else if (!Directory.Exists(project.SdkRootPath))
    {
        Console.Error.WriteLine("SDK 根目录不存在: " + project.SdkRootPath);
        return 2;
    }
}

await using (var dbPurge = await dbFactory.CreateDbContextAsync())
{
    var stale = await dbPurge.LlTestCases
        .Where(c => c.SourceFile != null && c.SourceFile != "")
        .Select(c => new { c.Id, c.SourceFile, c.FunctionName })
        .ToListAsync();
    var purgeIds = stale
        .Where(c => !SdkLlSourceFilter.IsInlineAvailableInSdk(c.SourceFile, c.FunctionName))
        .Select(c => c.Id)
        .ToList();
    if (purgeIds.Count > 0)
    {
        var n = await store.DeleteManyAsync(purgeIds);
        Console.WriteLine($"已删除 SDK 不可用 inline 用例: {n}（#if 0 等）");
    }
}

List<CaseRow> targets;
await using (var db = await dbFactory.CreateDbContextAsync())
{
    var runs = await db.LlTestRuns.AsNoTracking()
        .Include(r => r.TestCase)
        .OrderByDescending(r => r.StartedAtUtc)
        .ToListAsync();
    var latest = new Dictionary<Guid, LlTestRun>();
    foreach (var r in runs)
    {
        if (!latest.ContainsKey(r.LlTestCaseId))
            latest[r.LlTestCaseId] = r;
    }

    var onlyErrors = args.Contains("--errors-only");
    var onlyFailed = args.Contains("--failed-only");
    targets = latest.Values
        .Where(r => r.Status != nameof(LlTestRunStatus.Passed))
        .Where(r => !onlyErrors || r.Status == nameof(LlTestRunStatus.Error))
        .Where(r => !onlyFailed || r.Status == nameof(LlTestRunStatus.Failed))
        .Select(r => new CaseRow(
            r.LlTestCaseId,
            r.TestCase!.PeripheralName ?? "?",
            r.TestCase.FunctionName,
            r.TestCase.Name,
            r.TestCase.IsAutoGenerated,
            r.Status))
        .ToList();
}

Console.WriteLine($"待处理非 Passed 用例: {targets.Count}");
if (targets.Count == 0)
    return 0;

Guid sdkProjectId;
await using (var dbProbe = await dbFactory.CreateDbContextAsync())
    sdkProjectId = await dbProbe.SdkProjects.Select(x => x.Id).FirstAsync();

var regenPeripherals = targets
    .Where(t => t.IsAutoGenerated && t.PeripheralName is "GPIO" or "CORTEX" or "ADC" or "CMP" or "IIR" or "WWDG")
    .Select(t => t.PeripheralName)
    .Distinct()
    .ToList();

var caseIdsToRun = new List<Guid>();

foreach (var peri in regenPeripherals)
{
    var subset = targets.Where(t => t.PeripheralName == peri).ToList();
    var keys = subset.Select(t => (t.FunctionName, t.Name)).ToList();
    var deleteIds = subset.Select(t => t.Id).ToList();
    Console.WriteLine($"[{peri}] 删除 {deleteIds.Count} 条旧自动生成用例并重新生成…");
    await store.DeleteManyAsync(deleteIds);

    var (processed, saved) = await engine.GenerateAndSaveForPeripheralAsync(sdkProjectId, peri);
    var marked = await store.MarkFilteredReadyAsync(sdkProjectId, peri);
    Console.WriteLine($"[{peri}] 函数 {processed}，新写入 {saved}，标 Ready {marked}");

    await using var db = await dbFactory.CreateDbContextAsync();
    foreach (var key in keys)
    {
        var row = await db.LlTestCases.AsNoTracking()
            .Where(c => c.SdkProjectId == sdkProjectId
                        && c.PeripheralName == peri
                        && c.FunctionName == key.FunctionName
                        && c.Name == key.Name)
            .Select(c => c.Id)
            .FirstOrDefaultAsync();
        if (row == Guid.Empty)
        {
            row = await db.LlTestCases.AsNoTracking()
                .Where(c => c.SdkProjectId == sdkProjectId
                            && c.PeripheralName == peri
                            && c.FunctionName == key.FunctionName)
                .OrderBy(c => c.Name)
                .Select(c => c.Id)
                .FirstAsync();
            Console.WriteLine($"  警告: 未按名称匹配 {key.Name}，改用同名函数首条 {key.FunctionName}");
        }

        caseIdsToRun.Add(row);
    }

    targets.RemoveAll(t => t.PeripheralName == peri);
}

caseIdsToRun.AddRange(targets.Select(t => t.Id));
caseIdsToRun = caseIdsToRun.Distinct().ToList();
Console.WriteLine($"开始重跑 {caseIdsToRun.Count} 条…");

var clang = await engine.CheckCompilerAsync(sdkProjectId);
if (!clang.ClangFound)
{
    Console.WriteLine("未找到 Clang，尝试使用内置路径…");
    await using var db = await dbFactory.CreateDbContextAsync();
    var ep = TAE32.LLVirtualTest.Infrastructure.TestEngine.ClangCompilerService.EmbeddedClangPath;
    if (File.Exists(ep))
    {
        var compiler = sp.GetRequiredService<ICompilerService>();
        await compiler.SaveClangPathAsync(ep, CancellationToken.None);
        clang = await engine.CheckCompilerAsync(sdkProjectId);
    }
}

if (!clang.ClangFound)
{
    Console.Error.WriteLine("Clang 仍不可用，中止。");
    return 3;
}

Console.WriteLine(clang.Summary);

var sw = Stopwatch.StartNew();
var progress = new Progress<string>(m => Console.WriteLine(m));
var results = await engine.RunManyAsync(caseIdsToRun, progress);
sw.Stop();

var tally = results.GroupBy(r => r.Status).ToDictionary(g => g.Key.ToString(), g => g.Count());
Console.WriteLine();
Console.WriteLine($"完成，耗时 {sw.Elapsed:mm\\:ss}");
foreach (var kv in tally.OrderByDescending(x => x.Value))
    Console.WriteLine($"  {kv.Key}: {kv.Value}");

var fail = results.Count(r => r.Status != LlTestRunStatus.Passed);
return fail > 0 ? 10 : 0;

file sealed record CaseRow(
    Guid Id,
    string PeripheralName,
    string FunctionName,
    string Name,
    bool IsAutoGenerated,
    string LastStatus);
