# -*- coding: utf-8 -*-
import re
import sqlite3
from collections import Counter, defaultdict

DB = r"d:\Code\12_TAE32_LL_Virtual_Test\Publish\data\tae32_ll_virtual_test.db"

PROGRAM_PATTERNS = [
    ("compile_fail", re.compile(r"编译失败")),
    ("clang_env", re.compile(r"Clang 不可用")),
    ("harness_nrc", re.compile(r"harness tae32_run 返回")),
    ("access_violation", re.compile(r"AccessViolation|-1073741819")),
    ("timeout_exec", re.compile(r"执行超过")),
    ("exec_exception", re.compile(r"^执行异常:|InvalidOperationException")),
    ("pointer_skip_old", re.compile(r"指针参数|物化|Unsupported|return -2")),
    ("host_skip_policy", re.compile(r"DescribeSkip|Unsupported.*未执行")),
    ("native_skip_ave", re.compile(r"原生执行触达宿主无法映射")),
]

CASE_PATTERNS = [
    ("assert_reg_missing", re.compile(r"寄存器不存在")),
    ("assert_reg_mismatch", re.compile(r"寄存器值不匹配|值不匹配")),
    ("assert_return", re.compile(r"返回值")),
    ("clear_check_skip", re.compile(r"clear-check.*不存在|自动 clear-check")),
    ("assert_timeout", re.compile(r"Timeout|超时.*断言|超过.*ms")),
    ("assert_other", re.compile(r"断言")),
]


def classify(reason, status):
    r = reason or ""
    for key, pat in PROGRAM_PATTERNS:
        if pat.search(r):
            return "program", key
    for key, pat in CASE_PATTERNS:
        if pat.search(r):
            return "case", key
    if status == "Skipped":
        if "clear-check" in r:
            return "case", "clear_check_skip"
        if not r:
            return "unknown", "skipped_empty_reason"
        return "mixed", "skipped_other"
    return "unknown", r[:72] if r else "(empty)"


def main() -> None:
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    cur = con.cursor()

    cur.execute("SELECT Status, COUNT(*) n FROM LlTestRuns GROUP BY Status ORDER BY n DESC")
    status = cur.fetchall()
    total = sum(r["n"] for r in status)
    print("=== 运行状态 ===", "total", total)
    for r in status:
        pct = 100 * r["n"] / total if total else 0
        print(f"  {r['Status']}: {r['n']} ({pct:.1f}%)")

    cur.execute(
        """
        SELECT r.Status, r.FailureReason, r.CompileSucceeded,
               c.IsAutoGenerated, c.Name, c.FunctionName, c.PeripheralName
        FROM LlTestRuns r
        JOIN LlTestCases c ON c.Id = r.LlTestCaseId
        WHERE r.Status != 'Passed'
        """
    )
    rows = cur.fetchall()

    by_class: Counter = Counter()
    by_status_class: Counter = Counter()
    by_peri: Counter = Counter()
    samples: dict[tuple[str, str], list] = defaultdict(list)

    for row in rows:
        kind, key = classify(row["FailureReason"], row["Status"])
        by_class[(kind, key)] += 1
        by_status_class[(row["Status"], kind, key)] += 1
        if len(samples[(kind, key)]) < 2:
            samples[(kind, key)].append(row)
        if kind == "program":
            by_peri[(row["PeripheralName"], key)] += 1

    prog = sum(v for (k, _), v in by_class.items() if k == "program")
    case = sum(v for (k, _), v in by_class.items() if k == "case")
    mixed = sum(v for (k, _), v in by_class.items() if k == "mixed")
    unk = sum(v for (k, _), v in by_class.items() if k == "unknown")
    n = len(rows)

    print()
    print("=== 非 Passed 归类 (n=%d) ===" % n)
    print(f"  程序/引擎侧: {prog} ({100*prog/n:.1f}%)")
    print(f"  用例/断言侧: {case} ({100*case/n:.1f}%)")
    print(f"  混合(Skipped等): {mixed} ({100*mixed/n:.1f}%)")
    print(f"  未归类: {unk} ({100*unk/n:.1f}%)")

    print()
    print("=== 归类明细 Top 20 ===")
    for (kind, key), v in by_class.most_common(20):
        print(f"  [{kind}] {key}: {v}")

    print()
    print("=== Skipped FailureReason Top 12 ===")
    cur.execute(
        """
        SELECT FailureReason, COUNT(*) n
        FROM LlTestRuns WHERE Status = 'Skipped'
        GROUP BY FailureReason ORDER BY n DESC LIMIT 12
        """
    )
    for r in cur.fetchall():
        fr = r["FailureReason"] or "(null)"
        print(f"  {r['n']}: {fr[:140]}")

    print()
    cur.execute(
        """
        SELECT
          SUM(CASE WHEN CompileSucceeded=1 THEN 1 ELSE 0 END) compile_ok,
          SUM(CASE WHEN CompileSucceeded=0 THEN 1 ELSE 0 END) compile_fail
        FROM LlTestRuns WHERE Status = 'Error'
        """
    )
    er = cur.fetchone()
    print("=== Error 编译成功/失败 ===", dict(er))

    cur.execute(
        """
        SELECT c.PeripheralName, r.Status, COUNT(*) n
        FROM LlTestRuns r JOIN LlTestCases c ON c.Id=r.LlTestCaseId
        WHERE r.Status != 'Passed'
        GROUP BY 1, 2 ORDER BY n DESC LIMIT 15
        """
    )
    print()
    print("=== 非 Passed 外设×状态 Top ===")
    for r in cur.fetchall():
        print(f"  {r['PeripheralName']} / {r['Status']}: {r['n']}")

    cur.execute(
        """
        SELECT r.Status, c.IsAutoGenerated, COUNT(*) n
        FROM LlTestRuns r JOIN LlTestCases c ON c.Id=r.LlTestCaseId
        WHERE r.Status != 'Passed'
        GROUP BY 1, 2
        """
    )
    print()
    print("=== 非 Passed × 自动生成 ===")
    for r in cur.fetchall():
        print(f"  {r['Status']} auto={r['IsAutoGenerated']}: {r['n']}")

    print()
    print("=== 程序侧样例 ===")
    for (kind, key), v in by_class.items():
        if kind != "program":
            continue
        for s in samples[(kind, key)][:2]:
            fr = s["FailureReason"] or ""
            print(f"  [{key}] {s['FunctionName']} ({s['PeripheralName']}): {fr[:120]}")

    print()
    print("=== 用例侧 Failed 样例 (寄存器) ===")
    cur.execute(
        """
        SELECT c.FunctionName, c.Name, r.FailureReason
        FROM LlTestRuns r JOIN LlTestCases c ON c.Id=r.LlTestCaseId
        WHERE r.Status='Failed' AND r.FailureReason LIKE '%寄存器%'
        LIMIT 8
        """
    )
    for r in cur.fetchall():
        print(f"  {r['FunctionName']}: {(r['FailureReason'] or '')[:130]}")

    con.close()


if __name__ == "__main__":
    main()
